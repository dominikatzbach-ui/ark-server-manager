// ---- helpers ----------------------------------------------------------------

func writeTemp(t *testing.T, content string) string {
	t.Helper()
	tmp := filepath.Join(t.TempDir(), "test.ini")
	if err := os.WriteFile(tmp, []byte(content), 0644); err != nil {
		t.Fatalf("writeTemp: %v", err)
	}
	return tmp
}
